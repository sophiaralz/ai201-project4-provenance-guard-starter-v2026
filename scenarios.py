def _sample(name):
    return json.loads((_HERE / "samples" / f"{name}.json").read_text())["text"]


def _attack_text(attack_id, drop_first_paragraph=False):
    """A passage from the staff attack set — used only where it's plain human prose."""
    with (_HERE / "attack_set" / "attacks.csv").open(newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["id"] == attack_id:
                text = row["text"]
                return text.split("\n\n", 1)[1] if drop_first_paragraph else text
    raise KeyError(attack_id)


